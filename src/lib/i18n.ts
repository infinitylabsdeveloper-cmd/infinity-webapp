/**
 * Robust fallback getter that ensures:
 * 1. Missing keys automatically resolve to English.
 * 2. Never returns empty string or undefined for supported keys.
 */
export function getTranslation(lang: LanguageCode): Record<string, string> {
  const current = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const fallback = TRANSLATIONS.en;
  
  return new Proxy(current, {
    get(target, prop: string) {
      if (typeof prop === 'string') {
        return target[prop] || fallback[prop] || prop;
      }
      return (target as any)[prop];
    }
  });
}
